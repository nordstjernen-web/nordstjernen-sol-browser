#!/usr/bin/env python3
"""gen-temporal-windows-zones.py — generates the Windows-to-IANA time zone tables (default and per-region) from CLDR windowsZones.xml."""
import re
import sys
import urllib.request
from pathlib import Path

CLDR_RELEASE = "release-48"
URL = ("https://raw.githubusercontent.com/unicode-org/cldr/"
       f"{CLDR_RELEASE}/common/supplemental/windowsZones.xml")
OUT = Path(__file__).resolve().parent.parent / "src" / "quickjs" / "quickjs-temporal-winzones.h"


def load():
    if len(sys.argv) > 1:
        return Path(sys.argv[1]).read_text(encoding="utf-8")
    with urllib.request.urlopen(URL) as r:
        return r.read().decode("utf-8")


def main():
    xml = load()
    pairs = re.findall(r'<mapZone other="([^"]+)" territory="001" type="([^"]+)"/>', xml)
    pairs.sort(key=lambda p: p[0].lower())
    default = dict(pairs)
    regional = []
    for windows, region, iana in re.findall(
            r'<mapZone other="([^"]+)" territory="([A-Z]{2})" type="([^"]+)"/>', xml):
        first = iana.split()[0]
        if region != "ZZ" and default.get(windows) not in (None, first):
            regional.append((windows, region, first))
    regional.sort(key=lambda r: (r[0].lower(), r[1]))
    lines = [
        "/* quickjs-temporal-winzones.h — Windows time zone names to IANA identifiers "
        f"(generated by scripts/gen-temporal-windows-zones.py from CLDR {CLDR_RELEASE}). */",
        "static const char *const tp_windows_zones[][2] = {",
    ]
    for windows, iana in pairs:
        lines.append(f'    {{ "{windows}", "{iana}" }},')
    lines.append("};")
    lines.append("static const char *const tp_windows_zone_regions[][3] = {")
    for windows, region, iana in regional:
        lines.append(f'    {{ "{windows}", "{region}", "{iana}" }},')
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(pairs)} mappings and {len(regional)} regional overrides to {OUT}")


if __name__ == "__main__":
    main()
