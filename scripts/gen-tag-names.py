#!/usr/bin/env python3
"""Generate src/tag_names.h, the C tag ids, from the tag table in src/html5_rs/tags.rs.

Usage: gen-tag-names.py [TAGS_RS] [OUT]

The ids follow the order of the Rust Tag enum, shifted by one so that 0 is
NS_TAG_UNKNOWN: the HTML parser hands the C sink the Rust discriminant plus
one, and a node whose name is not in the table gets NS_TAG_UNKNOWN.
"""
import os
import re
import sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, "src/html5_rs/tags.rs")
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(root, "src/tag_names.h")

text = open(src, encoding="utf-8").read()
body = text[text.index("tags! {") + len("tags! {"):]
body = body[:body.index("\n}")]
names = re.findall(r'^\s*[A-Za-z0-9]+ = b"([A-Za-z0-9-]+)" c"\1",$', body, re.M)
if len(names) != body.count(" = b\""):
    sys.exit("gen-tag-names: unexpected line in the tags! table")

ident = lambda n: "NS_TAG_" + re.sub(r"(?<=[a-z])(?=[A-Z])", "_", n).upper().replace("-", "_")
order = sorted(range(len(names)), key=lambda i: names[i])

lines = [
    "/* Nordstjernen — tag ids for the names in src/html5_rs/tags.rs, generated by scripts/gen-tag-names.py.",
    " * Copyright 2026 Andreas Røsdal",
    " * SPDX-License-Identifier: LicenseRef-NSL-1.0 OR GPL-3.0-or-later",
    " */",
    "",
    "#ifndef NS_TAG_NAMES_H",
    "#define NS_TAG_NAMES_H",
    "",
    "typedef enum ns_tag {",
    "    NS_TAG_UNKNOWN,",
]
lines += [f"    {ident(n)}," for n in names]
lines += [
    "    NS_TAG_COUNT,",
    "} ns_tag;",
    "",
    "#ifdef NS_TAG_NAMES_TABLE",
    "static const char *const ns_tag_names[NS_TAG_COUNT] = {",
    '    "",',
]
lines += [f'    "{n}",' for n in names]
lines += [
    "};",
    "",
    "static const unsigned short ns_tag_sorted[NS_TAG_COUNT - 1] = {",
]
lines += [f"    {ident(names[i])}," for i in order]
lines += [
    "};",
    "#endif",
    "",
    "#endif",
    "",
]
open(out, "w", encoding="utf-8").write("\n".join(lines))
