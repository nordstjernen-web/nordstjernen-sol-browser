#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum AttrNs {
    None,
    XLink,
    Xml,
    Xmlns,
}

static FOREIGN_ATTRS: [(&[u8], AttrNs, usize); 11] = [
    (b"xlink:actuate", AttrNs::XLink, 5),
    (b"xlink:arcrole", AttrNs::XLink, 5),
    (b"xlink:href", AttrNs::XLink, 5),
    (b"xlink:role", AttrNs::XLink, 5),
    (b"xlink:show", AttrNs::XLink, 5),
    (b"xlink:title", AttrNs::XLink, 5),
    (b"xlink:type", AttrNs::XLink, 5),
    (b"xml:lang", AttrNs::Xml, 3),
    (b"xml:space", AttrNs::Xml, 3),
    (b"xmlns", AttrNs::Xmlns, 0),
    (b"xmlns:xlink", AttrNs::Xmlns, 5),
];

pub fn svg_tag_name(lower: &[u8]) -> Option<&'static CStr> {
    SVG_TAG_NAMES
        .iter()
        .find(|(from, _)| *from == lower)
        .map(|(_, to)| *to)
}

pub fn svg_attr_name(lower: &[u8]) -> Option<&'static [u8]> {
    SVG_ATTR_NAMES
        .iter()
        .find(|(from, _)| *from == lower)
        .map(|(_, to)| *to)
}

pub fn foreign_attr(name: &[u8]) -> Option<(AttrNs, usize)> {
    FOREIGN_ATTRS
        .iter()
        .find(|(n, _, _)| *n == name)
        .map(|&(_, ns, prefix)| (ns, prefix))
}
