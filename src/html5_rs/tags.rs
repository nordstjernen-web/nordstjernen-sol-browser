use core::ffi::CStr;

macro_rules! tags {
    ($($id:ident = $bytes:literal $c:literal,)*) => {
        #[derive(Clone, Copy, PartialEq, Eq, Debug)]
        pub enum Tag {
            $($id,)*
            Other,
        }

        impl Tag {
            pub fn from_bytes(name: &[u8]) -> Tag {
                match name {
                    $($bytes => Tag::$id,)*
                    _ => Tag::Other,
                }
            }

            pub fn name(self) -> Option<&'static CStr> {
                match self {
                    $(Tag::$id => Some($c),)*
                    Tag::Other => None,
                }
            }
        }
    };
}

